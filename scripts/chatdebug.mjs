import puppeteer from 'puppeteer-core';
const [id, out] = process.argv.slice(2);
const browser = await puppeteer.launch({executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new'});
const page = await browser.newPage();
await page.setViewport({width: 1500, height: 900});
page.on('console', (m) => console.log('console', m.type(), m.text().slice(0, 200)));
page.on('pageerror', (e) => console.log('pageerror', e.message));
page.on('requestfailed', (r) => console.log('fail', r.url(), r.failure()?.errorText));
page.on('response', (r) => r.url().includes('/chat') && console.log('chat resp', r.status()));
await page.goto(`http://localhost:5175/#p/${id}`, {waitUntil: 'networkidle2'});
await page.waitForSelector('.chat-input textarea');
await page.type('.chat-input textarea', 'Video o spánku pro mladé.');
const dis = await page.$eval('.chat-input button', (b) => b.disabled);
console.log('tlačítko disabled', dis);
await page.click('.chat-input button');
await new Promise((r) => setTimeout(r, 30000));
await page.screenshot({path: out});
console.log('msgs', await page.$$eval('.msg', (m) => m.length));
await browser.close();
